def set_run(run, cn=CN_BODY, en="Times New Roman", size=12, bold=False, color=None):
    run.font.name = en
    run._element.rPr.rFonts.set(qn("w:eastAsia"), cn)
    run.font.size = Pt(size)
    run.font.bold = bold
    if color:
        run.font.color.rgb = RGBColor(*color)

def para(text, cn=CN_BODY, size=12, bold=False, align=None, indent=True,
         space_before=0, space_after=0, line=28, color=None):
    p = doc.add_paragraph()
    pf = p.paragraph_format
    if align is not None:
        p.alignment = align
    if indent:
        pf.first_line_indent = Pt(size * 2)
    pf.space_before = Pt(space_before)
    pf.space_after = Pt(space_after)
    pf.line_spacing = Pt(line)
    r = p.add_run(text)
    set_run(r, cn=cn, size=size, bold=bold, color=color)
    return p

def heading(text, level=1):
    if level == 1:
        return para(text, cn=CN_HEAD, size=16, bold=True, indent=False,
                    space_before=10, space_after=6, line=28)
    elif level == 2:
        return para(text, cn=CN_HEAD, size=14, bold=True, indent=False,
                    space_before=6, space_after=4, line=26)
    else:
        return para(text, cn=CN_HEAD, size=12, bold=True, indent=True,
                    space_before=4, space_after=2, line=26)

def caption(text):
    return para(text, cn=CN_HEAD, size=12, bold=True, align=WD_ALIGN_PARAGRAPH.CENTER,
                indent=False, space_before=4, space_after=2, line=24)

def note(text):
    return para(text, cn=CN_KAI, size=10.5, align=WD_ALIGN_PARAGRAPH.CENTER,
                indent=False, space_before=1, space_after=4, line=20,
                color=(0x55, 0x55, 0x55))

def make_table(headers, rows, col_widths=None):
    t = doc.add_table(rows=1, cols=len(headers))
    t.style = "Table Grid"
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    for i, h in enumerate(headers):
        c = t.rows[0].cells[i]
        c.text = ""
        p = c.paragraphs[0]
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
        r = p.add_run(h)
        set_run(r, cn=CN_HEAD, size=10.5, bold=True)
    for row in rows:
        cells = t.add_row().cells
        for i, val in enumerate(row):
            cells[i].text = ""
            p = cells[i].paragraphs[0]
            p.alignment = WD_ALIGN_PARAGRAPH.CENTER
            bold = str(val).startswith("**")
            r = p.add_run(str(val).lstrip("*"))
            set_run(r, cn=CN_BODY, size=10.5, bold=bold)
    if col_widths:
        for i, w in enumerate(col_widths):
            for row in t.rows:
                row.cells[i].width = Cm(w)
    return t

